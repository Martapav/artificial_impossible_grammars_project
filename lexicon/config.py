"""All numeric and structural parameters for lexicon generation.

Lexicon v0.3.0 (experiment.md §2.5, §2.6, §3): sampled open-class stems, derived
entries with order-bound affixes, partially length-orthogonal Zipf ranks.
This module configures v0.3.0 only. Lexicon v0.2.0 (enumerated stems, no affixes;
the file `lexicon.json`, which built corpora up to set_3) is generated by the
frozen, self-contained `lexicon/legacy_v020.py`, which does not read this config.
"""

VERSION: str = "0.3.0"

P_PROPER_LIKE: float = 0.1
P_CAT6_COMPATIBLE: float = 0.5
NULL_MORPHEME: str = "#NULL#"
SEPARATOR: str = "#"
CATEGORY_SIZE_CAPS: dict[str, int] = {}

# Zipf-Mandelbrot frequency parameters for open-class lexical sampling.
# s=1.0 is canonical Zipf (frequency ∝ 1/rank); q=0.0 means no Mandelbrot offset.
# Only open-class ENTRIES get frequency ranks; closed-class items (CAT4,
# CAT6, CAT8, CAT9, CAT1PRON, CAT3AUX) are selected by grammatical rule, not
# frequency, and keep zipf_rank=0 as a sentinel.
ZIPF_S: float = 1.0
ZIPF_Q: float = 0.0
ZIPF_CATEGORIES: tuple[str, ...] = ("CAT1", "CAT2", "CAT3", "CAT5")

# Letters reserved for lexical stems, partitioned by category.
# CAT1PRON, CAT4 use fixed forms (not combinatorial generation).
# CAT3AUX, CAT6, CAT8, CAT9 also have a hardcoded small inventory.
LETTER_PARTITIONS: dict[str, tuple[str, ...]] = {
    "CAT1":     ("a", "b", "c", "d", "e"),
    "CAT2":     ("f", "g", "h", "x"),
    "CAT3":     ("i", "j", "k", "l"),
    "CAT3AUX":  ("n",),
    "CAT4":     ("u", "v"),
    "CAT5":     ("o", "p", "q"),
    "CAT6":     ("r", "y", "z"),
    "CAT8":     ("w",),
    "CAT9":     ("s", "t"),
    "CAT1PRON": ("m", "mm"),
}

# Open (semantically loaded) categories: sampled stems + derivational affixes.
OPEN_CATEGORIES: tuple[str, ...] = ("CAT1", "CAT2", "CAT3", "CAT5")
# Kept as an alias: older code/tests import this name.
COMBINATORIAL_CATEGORIES: tuple[str, ...] = OPEN_CATEGORIES

# ── Lexicon magnitude (experiment.md §2.6) ───────────────────────────────────
# ~5,000 stems x 20 entries per stem = ~100k open-class entries (no inflection).
STEM_TARGET: int = 5000
ENTRIES_PER_STEM: int = 20

# Stems are split across categories in proportion to WordNet 3.0 unique strings
# (Princeton University, WordNet 3.0 database statistics, wnstats(7WN);
# adjectives include satellites). Verified by Marta 2026-11-24.
WORDNET_30_UNIQUE_STRINGS: dict[str, int] = {
    "CAT1": 117798,   # nouns
    "CAT2": 21479,    # adjectives (incl. satellites)
    "CAT3": 11529,    # verbs
    "CAT5": 4481,     # adverbs
}

# ── Derivational morphology (experiment.md §2.6) ─────────────────────────────
# Template: (PRE#)STEM(#S_inner)(#S_outer)#INFL...  -> at most 4 lexical morphemes.
# Suffixes are 3x prefixes in inventory and usage (direction: Greenberg 1957,
# "Order of affixing"; magnitude: design choice).
AFFIX_SLOTS: tuple[str, ...] = ("prefix", "suffix_inner", "suffix_outer")
AFFIX_INVENTORY: dict[str, dict[str, int]] = {
    "CAT1": {"prefix": 6, "suffix_inner": 6, "suffix_outer": 13},
    "CAT3": {"prefix": 6, "suffix_inner": 6, "suffix_outer": 13},
    "CAT2": {"prefix": 4, "suffix_inner": 4, "suffix_outer": 9},
    "CAT5": {"prefix": 4, "suffix_inner": 4, "suffix_outer": 9},
}
AFFIX_LENGTHS: tuple[int, ...] = (2, 3)     # affixes are 2-3 letters, never 1
P_SUFFIX_SIDE: float = 0.75                 # each affix -> suffix side w.p. 3/4
MAX_PREFIXES: int = 1
MAX_SUFFIXES: int = 2

# Share of ENTRIES by lexical-morpheme count (1 = bare stem). Mean 2.8.
# 0.05 follows from 1 bare entry per stem / ENTRIES_PER_STEM.
MORPH_SHARES: dict[int, float] = {1: 0.05, 2: 0.30, 3: 0.45, 4: 0.20}

# ── Stem length (experiment.md §2.2, §3 phase B) ─────────────────────────────
# Log-normal shape (median 4.8 letters, sigma 0.35) truncated by capacity: no
# length may use more than SHORT_LEN_CAP of its free strings (strings not
# reserved as affixes); the excess moves to longer lengths. STEM_LEN_MAX only
# bounds the computation (the log-normal mass beyond it is negligible).
STEM_LEN_LOGNORM_MEDIAN: float = 4.8
STEM_LEN_LOGNORM_SIGMA: float = 0.35
SHORT_LEN_CAP: float = 0.5
STEM_LEN_MAX: int = 14

# ── Frequency ranks (experiment.md §2.5) ─────────────────────────────────────
# score = N(0,1) + ZIPF_ALPHA * max(0, stem_len - pool) + ZIPF_BETA * n_affixes;
# entries ranked by ascending score (rank 1 = most frequent). Chosen 2026-11-23
# from a pre-generation usage simulation ("mild").
ZIPF_ALPHA: float = 0.5
ZIPF_BETA: float = 0.5

# CAT6 attachment partition (experiment.md §2.4). Two items are PP-under-NP
# (CAT1-selecting); one is PP-under-VP (CAT3-selecting). This is a fixed,
# deterministic assignment that all four grammars import.
CAT6_PP_UNDER_NP_LETTERS: tuple[str, ...] = ("r", "y")
CAT6_PP_UNDER_VP_LETTERS: tuple[str, ...] = ("z",)

# Digits reserved for inflectional morphemes, partitioned by parameter.
DIGIT_PARTITIONS: dict[str, tuple[str, ...]] = {
    "INFL1_gender":      ("1", "2"),
    "INFL1_number":      ("3", "4"),
    "INFL3_tense":       ("7", "8", "9"),
}
